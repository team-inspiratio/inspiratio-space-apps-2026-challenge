"""S10 score table: the top 3 experiments next to M1s and QM, with block-bootstrap intervals.

  uv run python -X utf8 -m harmonization.s10_scores      # writes reports/scores-s10.md and .json

"Top 3" = the three lowest combined validation MALE among the experiments that pass every
guardrail (harmonization/experiments.csv, eligible = yes). Each one is re-run from its exact
source on the exp/lightgbm branch (harmonization/variants/E###.py) with the frozen judge, so
the table also checks that experiments reproduce. The selection-rule check below is the
preregistration section 4 items 1-4 on the validation windows only; item 5 (leakage review)
is reports/model-review.md, and the final decision is S11's.
"""

from __future__ import annotations

import csv
import importlib.util
import json
import re
import subprocess
import sys

from harmonization import autoexp, evaluate, harmonize, prepare
from harmonization.config import ROOT

OUT_MD = ROOT / "reports" / "scores-s10.md"
OUT_JSON = ROOT / "reports" / "scores-s10.json"
BRANCH = "exp/lightgbm"


def load_variant(exp_id: str):
    """Import harmonization/variants/<exp_id>.py from the experiment branch as a module."""
    src = subprocess.run(
        ["git", "-C", str(ROOT), "show", f"{BRANCH}:harmonization/variants/{exp_id}.py"],
        check=True,
        capture_output=True,
    ).stdout
    path = autoexp.exp_dir() / "variants" / f"{exp_id}.py"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(src)
    spec = importlib.util.spec_from_file_location(f"variant_{exp_id}", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)  # type: ignore[union-attr]
    return mod


def top3() -> list[dict]:
    """Rows superseded by a 30-trial rerun ("Rerun of E### ...", ADR 0007 item 5) are left out:
    the rerun's own row (eligible or not) is the candidate's score."""
    with autoexp.CSV.open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    superseded = {m.group(1) for r in rows if (m := re.match(r"Rerun of (E\d+)", r["hypothesis"]))}
    rows = [r for r in rows if r["eligible"] == "yes" and r["exp_id"] not in superseded]
    rows.sort(key=lambda r: (float(r["combined_male"]), r["exp_id"]))
    return rows[:3]


def selection(res: dict, m1s: dict, vs: dict) -> dict:
    """Preregistration section 4 items 1-4 (validation windows only)."""
    fails = autoexp.guardrails(res, m1s)
    return {
        "1_improvement_10pct": res["combined_male"] <= 0.90 * m1s["combined_male"],
        "2_more_than_1_se": -vs["diff"] > vs["se"],
        "3_4_guardrails": not fails,
        "guardrail_failures": fails,
    }


def fmt_ci(d: dict) -> str:
    return f"{d['diff']:+.4f} ± {d['se']:.4f} [{d['ci95'][0]:+.4f}, {d['ci95'][1]:+.4f}]"


def main() -> int:
    df = prepare.load_grid()
    m1s = autoexp.strip(evaluate.evaluate(lambda t: harmonize.fit_m1s(t, 20.0), df))
    qm = autoexp.strip(evaluate.evaluate(harmonize.fit_qm, df))
    table = [("M1s λ=20", m1s, None), ("QM", qm, None)]
    out: dict = {"top3": []}
    for r in top3():
        mod = load_variant(r["exp_id"])
        res = autoexp.strip(evaluate.evaluate(mod.fit_lgb, df))
        vs_m1s, vs_qm = evaluate.bootstrap_diff(m1s, res), evaluate.bootstrap_diff(qm, res)
        reproduced = abs(res["combined_male"] - float(r["combined_male"])) < 5e-5
        out["top3"].append(
            {
                "exp_id": r["exp_id"],
                "hypothesis": r["hypothesis"],
                "combined_male": res["combined_male"],
                "csv_combined_male": float(r["combined_male"]),
                "reproduced": reproduced,
                "vs_m1s": vs_m1s,
                "vs_qm": vs_qm,
                "selection": selection(res, m1s, vs_m1s),
                "windows": {
                    w: {k: v for k, v in res[w].items() if k != "units"} for w in ("main", "aux")
                },
            }
        )
        table.append((f"LightGBM {r['exp_id']}", res, (vs_m1s, vs_qm)))
    out["m1s_combined"], out["qm_combined"] = m1s["combined_male"], qm["combined_male"]
    OUT_JSON.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    lines = [
        "# Score table S10: top 3 LightGBM vs M1s and QM",
        "",
        "Generated by `uv run python -X utf8 -m harmonization.s10_scores`; "
        "scored with the frozen grader code. "
        "Top 3 = among the experiments in `harmonization/experiments.csv` "
        "that pass every guardrail (eligible = yes) "
        "(original rows superseded by a 30-trial Optuna rerun do not count; ADR 0007 item 5), "
        "the three with the lowest combined validation MALE over both windows; "
        "each is rerun from its exact source on the `exp/lightgbm` branch. "
        "Difference = the method's MALE − the reference MALE "
        "(negative means LightGBM is better), "
        '"year × region" block resampling 2000 times, '
        "both windows weighted equally, "
        "written as difference ± standard error [95% interval]. No p-values are reported.",
        "",
        "## 1. Validation scores",
        "",
        "| Method | Combined MALE | main | aux "
        "| Zero hotspots Ĥ≥1 main/aux | Zero hotspots Ĥ≥5 main/aux "
        "| 1–9 hotspots MAE main/aux | Total bias main/aux "
        "| Difference vs M1s | Difference vs QM |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, res, vs in table:
        a, b = res["main"], res["aux"]
        lines.append(
            f"| {name} | {res['combined_male']:.4f} | {a['male']:.4f} | {b['male']:.4f} | "
            f"{a['zero_ge1']:.3f}/{b['zero_ge1']:.3f} | {a['zero_ge5']:.3f}/{b['zero_ge5']:.3f} | "
            f"{a['low_mae']:.2f}/{b['low_mae']:.2f} | "
            f"{a['total_bias_mean_abs']:.3f}/{b['total_bias_mean_abs']:.3f} | "
            + (f"{fmt_ci(vs[0])} | {fmt_ci(vs[1])} |" if vs else "— | — |")
        )
    lines += [
        "",
        "## 2. MALE by region",
        "",
        "| Method | Window | " + " | ".join(sorted(m1s["main"]["male_by_region"])) + " |",
        "|---|---|" + "---:|" * len(m1s["main"]["male_by_region"]),
    ]
    for name, res, _ in table:
        for w in ("main", "aux"):
            regs = res[w]["male_by_region"]
            lines.append(
                f"| {name} | {w} | " + " | ".join(f"{regs[k]:.4f}" for k in sorted(regs)) + " |"
            )
    lines += [
        "",
        "## 3. Preliminary check of the selection rule "
        "(pre-registration section 4, items 1–4, validation set only; "
        "item 5 is in `reports/model-review.md`; S11 makes the final decision)",
        "",
        "| Experiment | Rerun matches | ① At least 10% better "
        "| ② Improvement > 1 standard error | ③④ Guardrails | Failed items |",
        "|---|---|---|---|---|---|",
    ]
    yes = {True: "yes", False: "no"}
    for t in out["top3"]:
        s = t["selection"]
        lines.append(
            f"| {t['exp_id']} | {yes[t['reproduced']]} | {yes[s['1_improvement_10pct']]} | "
            f"{yes[s['2_more_than_1_se']]} | {yes[s['3_4_guardrails']]} | "
            f"{'; '.join(s['guardrail_failures']) or '—'} |"
        )
    lines += ["", "Hypotheses of the top 3:", ""]
    lines += [f"- **{t['exp_id']}**: {t['hypothesis']}" for t in out["top3"]]
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT_MD.relative_to(ROOT)}; top 3: {[t['exp_id'] for t in out['top3']]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
